def test_calculate_smas_with_sufficient_data(sample_stock_data):
    """
    Tests SMA calculation with sufficient data.
    """
    # Calculate SMAs
    result_df = calculate_smas(sample_stock_data)
    
    # Check that SMA columns were added
    short_window = settings.SHORT_SMA_WINDOW
    long_window = settings.LONG_SMA_WINDOW
    
    assert f"SMA_{short_window}" in result_df.columns
    assert f"SMA_{long_window}" in result_df.columns
    
    # Check that NaN values are present for the first N-1 rows
    # (where N is the window size)
    assert result_df[f"SMA_{short_window}"].iloc[:short_window-1].isna().all()
    assert result_df[f"SMA_{long_window}"].iloc[:long_window-1].isna().all()
    
    # Check that values are calculated correctly for a few points
    # For a simple linear price increase, the SMA should be the average
    # of the window, which is the middle point's value
    
    # For 50-day SMA at day 75, it should be close to the price at day 50
    # (since prices increase linearly)
    expected_short_sma = 102.55 # Average of prices from index 1 to 50
    assert abs(result_df[f"SMA_{short_window}"].iloc[short_window] - expected_short_sma) < 0.01
    
    # For 200-day SMA at day 250, it should be close to the price at day 150
    expected_long_sma = 110.05 # Average of prices from index 1 to 200
    assert abs(result_df[f"SMA_{long_window}"].iloc[long_window] - expected_long_sma) < 0.01


