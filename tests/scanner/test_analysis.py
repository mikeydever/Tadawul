def test_check_approaching_golden_cross_not_rising():
    """
    Tests approaching golden cross detection with SMAs within threshold but not rising.
    """
    # Create a DataFrame with SMAs close together but not consistently rising
    dates = pd.date_range(start="2023-01-01", periods=settings.TREND_DAYS + 5, freq="D")
    short_window = settings.SHORT_SMA_WINDOW
    long_window = settings.LONG_SMA_WINDOW
    
    # Create short SMA values that are within threshold but not consistently rising
    long_sma_value = 100.0
    gap_pct = settings.APPROACHING_THRESHOLD / 2
    gap = long_sma_value * (gap_pct / 100)
    
    # Create fluctuating short SMA values (not consistently rising)
    short_sma_values = []
    for i in range(settings.TREND_DAYS + 5):
        # Add some oscillation to make it not consistently rising
        if i % 2 == 0:
            short_sma_values.append(long_sma_value - gap + (i * 0.1))
        else:
            short_sma_values.append(long_sma_value - gap - (i * 0.05))
    
    df = pd.DataFrame(
        {
            "Close": [100 + i for i in range(settings.TREND_DAYS + 5)],
            f"SMA_{short_window}": short_sma_values,
            f"SMA_{long_window}": [long_sma_value for _ in range(settings.TREND_DAYS + 5)],
        },
        index=dates,
    )
    
    # Check for approaching golden cross
    result = check_approaching_golden_cross(df)
    
    # Should return False since short SMA is not consistently rising
    assert result is False